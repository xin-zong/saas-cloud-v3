ALTER TABLE alarm_action_event ALTER COLUMN actor_id DROP NOT NULL;
ALTER TABLE alarm_action_event ADD COLUMN actor_type text NOT NULL DEFAULT 'user' CHECK(actor_type IN ('user','engine'));
ALTER TABLE alarm_action_event ADD CONSTRAINT alarm_action_actor CHECK
 ((actor_type='user' AND actor_id IS NOT NULL) OR (actor_type='engine' AND actor_id IS NULL));

CREATE TABLE alarm_rule_execution (
 rule_id bigint PRIMARY KEY REFERENCES alarm_rule_config(id),rule_version bigint NOT NULL,
 mapping_key text NOT NULL DEFAULT '',last_bucket_ms bigint NOT NULL DEFAULT -1,
 consecutive integer NOT NULL DEFAULT 0 CHECK(consecutive>=0),normal_since_ms bigint,
 latched boolean NOT NULL DEFAULT false,status text NOT NULL,reason text NOT NULL,
 checked_at timestamptz NOT NULL,evidence jsonb NOT NULL DEFAULT '[]'
);
CREATE TABLE alarm_rule_occurrence (
 alarm_id bigint PRIMARY KEY REFERENCES alarm(id),rule_id bigint NOT NULL REFERENCES alarm_rule_config(id),
 rule_version bigint NOT NULL,station_id bigint NOT NULL REFERENCES station(id),
 mapping_key text NOT NULL,rule_snapshot jsonb NOT NULL,
 trigger_evidence jsonb NOT NULL,recovery_evidence jsonb,ended_at timestamptz
);
CREATE UNIQUE INDEX alarm_rule_one_active ON alarm_rule_occurrence(rule_id) WHERE ended_at IS NULL;
CREATE TABLE alarm_detection_event (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rule_id bigint NOT NULL REFERENCES alarm_rule_config(id),rule_version bigint NOT NULL,
 alarm_id bigint REFERENCES alarm(id),bucket_ms bigint NOT NULL,status text NOT NULL,
 reason text NOT NULL,evidence jsonb NOT NULL,processed_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(rule_id,rule_version,bucket_ms)
);
CREATE INDEX alarm_detection_history ON alarm_detection_event(rule_id,id DESC);
-- Retain the original station of a rule event after asset movement, as for EMS-origin events.
CREATE VIEW alarm_business_origin AS
 SELECT alarm_id,station_id FROM ems_alarm_business_origin
 UNION ALL SELECT alarm_id,station_id FROM alarm_rule_occurrence;
