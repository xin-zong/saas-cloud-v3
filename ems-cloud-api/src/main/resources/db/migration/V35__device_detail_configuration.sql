-- Local presentation and analysis/nameplate settings only. Never commands or live observations.
CREATE TABLE device_detail_configuration (
 device_id bigint PRIMARY KEY REFERENCES device(id) ON DELETE RESTRICT,
 version bigint NOT NULL DEFAULT 0 CHECK(version>=0),
 selected_point_ids jsonb NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(selected_point_ids)='array' AND jsonb_array_length(selected_point_ids)<=12),
 theory_values jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(theory_values)='object'),
 updated_by bigint REFERENCES app_user(id),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE device_detail_configuration_event (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 device_id bigint NOT NULL REFERENCES device(id) ON DELETE RESTRICT,
 station_id bigint NOT NULL REFERENCES station(id),
 actor_id bigint NOT NULL REFERENCES app_user(id),
 version bigint NOT NULL,
 selected_point_ids jsonb NOT NULL,
 theory_values jsonb NOT NULL,
 occurred_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(device_id,version)
);
CREATE INDEX device_detail_configuration_event_device_time ON device_detail_configuration_event(device_id,occurred_at DESC);
