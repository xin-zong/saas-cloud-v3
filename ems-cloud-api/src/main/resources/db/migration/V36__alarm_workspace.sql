ALTER TABLE alarm ADD COLUMN deleted_at timestamptz;
ALTER TABLE alarm ADD COLUMN deleted_by bigint REFERENCES app_user(id);
ALTER TABLE alarm ADD CONSTRAINT alarm_closed_actor CHECK((closed_at IS NULL)=(closed_by IS NULL));
ALTER TABLE alarm ADD CONSTRAINT alarm_deleted_actor CHECK((deleted_at IS NULL)=(deleted_by IS NULL));
CREATE TABLE alarm_read_receipt (
 alarm_id bigint NOT NULL REFERENCES alarm(id),user_id bigint NOT NULL REFERENCES app_user(id),
 read_at timestamptz NOT NULL DEFAULT now(),PRIMARY KEY(alarm_id,user_id)
);
CREATE TABLE alarm_action_event (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,alarm_id bigint NOT NULL REFERENCES alarm(id),
 actor_id bigint NOT NULL REFERENCES app_user(id),action varchar(30) NOT NULL,
 note text NOT NULL DEFAULT '',version bigint NOT NULL,occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX alarm_action_history ON alarm_action_event(alarm_id,id);
CREATE TABLE alarm_rule_config (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,station_id bigint NOT NULL REFERENCES station(id),
 name varchar(120) NOT NULL CHECK(btrim(name)<>''),object_type varchar(16) NOT NULL CHECK(object_type IN ('STATION','DEVICE')),
 device_id bigint REFERENCES device(id),severity varchar(20) NOT NULL CHECK(severity IN ('critical','warning','info')),
 conditions jsonb NOT NULL CHECK(jsonb_typeof(conditions)='array' AND jsonb_array_length(conditions) BETWEEN 1 AND 10),
 effective_start integer NOT NULL CHECK(effective_start BETWEEN 0 AND 1425 AND effective_start%15=0),
 effective_end integer NOT NULL CHECK(effective_end BETWEEN 15 AND 1440 AND effective_end%15=0),
 recovery_duration integer NOT NULL CHECK(recovery_duration BETWEEN 0 AND 86400),
 solution text NOT NULL DEFAULT '',notification jsonb NOT NULL CHECK(jsonb_typeof(notification)='object'),
 enabled boolean NOT NULL DEFAULT true,version bigint NOT NULL DEFAULT 1 CHECK(version>0),
 created_by bigint NOT NULL REFERENCES app_user(id),updated_by bigint NOT NULL REFERENCES app_user(id),
 created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now(),deleted_at timestamptz,
 CHECK(effective_end>effective_start),CHECK((object_type='DEVICE')=(device_id IS NOT NULL))
);
CREATE TABLE alarm_rule_revision (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,rule_id bigint NOT NULL REFERENCES alarm_rule_config(id),
 actor_id bigint NOT NULL REFERENCES app_user(id),action varchar(30) NOT NULL,version bigint NOT NULL,
 snapshot jsonb NOT NULL,occurred_at timestamptz NOT NULL DEFAULT now(),UNIQUE(rule_id,version)
);
CREATE INDEX alarm_rule_station ON alarm_rule_config(station_id,id) WHERE deleted_at IS NULL;

