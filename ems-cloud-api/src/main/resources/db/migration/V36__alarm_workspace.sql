ALTER TABLE alarm ADD COLUMN source varchar(16) NOT NULL DEFAULT 'device' CHECK(source IN ('device','rule'));
ALTER TABLE alarm ADD COLUMN version bigint NOT NULL DEFAULT 1 CHECK(version>0);
ALTER TABLE alarm ADD COLUMN closed_at timestamptz;
