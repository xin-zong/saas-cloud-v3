CREATE FUNCTION check_ems_parent_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME='ems_gateway' THEN
        IF NEW.device_id<>OLD.device_id THEN
            RAISE EXCEPTION 'EMS asset identity is immutable' USING ERRCODE='23514';
        END IF;
    ELSIF TG_TABLE_NAME='measurement_point' THEN
        IF NEW.device_id<>OLD.device_id AND EXISTS(SELECT 1 FROM point_binding WHERE measurement_point_id=OLD.id) THEN
            RAISE EXCEPTION 'Mapped measurement asset identity is immutable' USING ERRCODE='23514';
        END IF;
    ELSIF TG_TABLE_NAME='ems_binding_period' THEN
        PERFORM pg_advisory_xact_lock(hashtextextended(NEW.ems_uuid::text,78291029));
        IF EXISTS(SELECT 1 FROM structure_acceptance WHERE binding_period_id=NEW.id AND
           (received_at<NEW.valid_from OR (NEW.valid_to IS NOT NULL AND received_at>=NEW.valid_to))) OR
           EXISTS(SELECT 1 FROM config_acceptance WHERE binding_period_id=NEW.id AND
           (received_at<NEW.valid_from OR (NEW.valid_to IS NOT NULL AND received_at>=NEW.valid_to))) THEN
            RAISE EXCEPTION 'Period change would invalidate accepted version receipt' USING ERRCODE='23514';
        END IF;
        IF EXISTS(SELECT 1 FROM device_binding WHERE binding_period_id=NEW.id AND NOT(tstzrange(valid_from,valid_to,'[)') <@ tstzrange(NEW.valid_from,NEW.valid_to,'[)'))) THEN
            RAISE EXCEPTION 'Close child device bindings before closing EMS period' USING ERRCODE='23514';
        END IF;
    ELSIF TG_TABLE_NAME='device_binding' THEN
        IF (NEW.binding_period_id,NEW.scope,NEW.cabinet_no,NEW.role,NEW.local_no,NEW.device_id,NEW.valid_from) IS DISTINCT FROM
        (OLD.binding_period_id,OLD.scope,OLD.cabinet_no,OLD.role,OLD.local_no,OLD.device_id,OLD.valid_from) OR
        EXISTS(SELECT 1 FROM point_binding WHERE device_binding_id=NEW.id AND NOT(tstzrange(valid_from,valid_to,'[)') <@ tstzrange(NEW.valid_from,NEW.valid_to,'[)'))) THEN
            RAISE EXCEPTION 'Binding identity is immutable; close child point bindings first' USING ERRCODE='23514';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER ems_gateway_identity BEFORE UPDATE ON ems_gateway FOR EACH ROW EXECUTE FUNCTION check_ems_parent_change();
CREATE TRIGGER ems_point_asset_identity BEFORE UPDATE OF device_id ON measurement_point FOR EACH ROW EXECUTE FUNCTION check_ems_parent_change();
