    last_fresh_heartbeat timestamptz,
    lease_owner text,
    lease_until timestamptz,
    fencing_token ems_counter NOT NULL DEFAULT 0,
    CHECK((lease_owner IS NULL)=(lease_until IS NULL)),
    CHECK(lease_owner IS NULL OR btrim(lease_owner)<>''),
    CHECK((connection_id IS NULL)=(ingress_generation IS NULL)),
    CHECK(connection_id IS NOT NULL OR last_fresh_heartbeat IS NULL)
);
