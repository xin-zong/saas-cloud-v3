-- Aggregate only persisted evidence; no fabricated Kafka lag or successful-send metric.
CREATE VIEW ems_ingestion_status AS
 SELECT r.ems_uuid,r.binding_period_id,p.station_id,
        count(*) AS saved_objects,
        count(*) FILTER (WHERE r.status='projected') AS projected_objects,
        count(*) FILTER (WHERE r.status='projection_failed') AS projection_failures,
        count(*) FILTER (WHERE r.type='important_history') AS saved_history_parts,
        max(r.received_at) AS last_saved_at
 FROM reliable_message r
 JOIN ems_binding_period p ON p.id=r.binding_period_id
 GROUP BY r.ems_uuid,r.binding_period_id,p.station_id;

-- Worker acceptance and management period edits share the gateway advisory lock.
-- Invoker-rights reads here need SELECT only; no worker asset UPDATE privilege.
CREATE FUNCTION check_ems_version_acceptance() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    period ems_binding_period;
    version_ems uuid;
BEGIN
    SELECT * INTO period FROM ems_binding_period WHERE id=NEW.binding_period_id;
    IF period.id IS NULL THEN
        RAISE EXCEPTION 'Acceptance binding period missing' USING ERRCODE='23503';
    END IF;
    PERFORM pg_advisory_xact_lock(hashtextextended(period.ems_uuid::text,78291029));
    SELECT * INTO period FROM ems_binding_period WHERE id=NEW.binding_period_id;
    IF NEW.received_at<period.valid_from OR
       (period.valid_to IS NOT NULL AND NEW.received_at>=period.valid_to) THEN
        RAISE EXCEPTION 'Receipt outside binding period' USING ERRCODE='23514';
    END IF;
    IF TG_TABLE_NAME='structure_acceptance' THEN
        SELECT ems_uuid INTO version_ems FROM structure_revision WHERE id=NEW.revision_id;
    ELSE
        SELECT ems_uuid INTO version_ems FROM config_revision WHERE id=NEW.revision_id;
    END IF;
    IF version_ems IS DISTINCT FROM period.ems_uuid THEN
        RAISE EXCEPTION 'Accepted version EMS mismatch' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER ems_structure_acceptance BEFORE INSERT ON structure_acceptance
    FOR EACH ROW EXECUTE FUNCTION check_ems_version_acceptance();
CREATE TRIGGER ems_config_acceptance BEFORE INSERT ON config_acceptance
    FOR EACH ROW EXECUTE FUNCTION check_ems_version_acceptance();

CREATE FUNCTION check_ems_immutable_version_fact() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW IS DISTINCT FROM OLD THEN
        RAISE EXCEPTION 'Version content and acceptance facts are immutable' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER ems_structure_immutable BEFORE UPDATE ON structure_revision
    FOR EACH ROW EXECUTE FUNCTION check_ems_immutable_version_fact();
CREATE TRIGGER ems_config_immutable BEFORE UPDATE ON config_revision
    FOR EACH ROW EXECUTE FUNCTION check_ems_immutable_version_fact();
CREATE TRIGGER ems_config_value_immutable BEFORE UPDATE ON config_value
    FOR EACH ROW EXECUTE FUNCTION check_ems_immutable_version_fact();
CREATE TRIGGER ems_bmu_layout_immutable BEFORE UPDATE ON bmu_layout
    FOR EACH ROW EXECUTE FUNCTION check_ems_immutable_version_fact();
CREATE TRIGGER ems_structure_acceptance_immutable BEFORE UPDATE ON structure_acceptance
    FOR EACH ROW EXECUTE FUNCTION check_ems_immutable_version_fact();
CREATE TRIGGER ems_config_acceptance_immutable BEFORE UPDATE ON config_acceptance
    FOR EACH ROW EXECUTE FUNCTION check_ems_immutable_version_fact();
