-- Lock the asset row when validating current station ownership, so a concurrent move cannot bypass validation.
CREATE FUNCTION check_ems_binding_period() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    asset_station bigint;
BEGIN
    IF TG_OP='UPDATE' AND (NEW.ems_uuid,NEW.station_id,NEW.valid_from) IS DISTINCT FROM (OLD.ems_uuid,OLD.station_id,OLD.valid_from) THEN
        RAISE EXCEPTION 'Binding historical identity is immutable' USING ERRCODE='23514';
    END IF;
    SELECT d.station_id INTO asset_station FROM device d JOIN ems_gateway g ON g.device_id=d.id WHERE g.ems_uuid=NEW.ems_uuid FOR UPDATE OF d;
    IF (TG_OP='INSERT' OR NEW.valid_to IS NULL) AND NEW.station_id IS DISTINCT FROM asset_station THEN
        RAISE EXCEPTION 'EMS station mismatch' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER ems_period_station BEFORE INSERT OR UPDATE ON ems_binding_period FOR EACH ROW EXECUTE FUNCTION check_ems_binding_period();
CREATE FUNCTION check_ems_device_binding() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    period ems_binding_period;
    asset_station bigint;
BEGIN
    SELECT * INTO period FROM ems_binding_period WHERE id=NEW.binding_period_id FOR SHARE;
    SELECT station_id INTO asset_station FROM device WHERE id=NEW.device_id FOR UPDATE;
    IF period.id IS NULL OR asset_station IS DISTINCT FROM period.station_id OR NOT (tstzrange(NEW.valid_from,NEW.valid_to,'[)') <@ tstzrange(period.valid_from,period.valid_to,'[)')) THEN
        RAISE EXCEPTION 'Device binding station or period mismatch' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER ems_device_binding_guard BEFORE INSERT OR UPDATE ON device_binding FOR EACH ROW EXECUTE FUNCTION check_ems_device_binding();
CREATE FUNCTION check_ems_asset_move() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.station_id IS DISTINCT FROM OLD.station_id AND
    (EXISTS(SELECT 1 FROM ems_binding_period p JOIN ems_gateway g USING(ems_uuid) WHERE g.device_id=OLD.id AND p.valid_to IS NULL) OR
    EXISTS(SELECT 1 FROM device_binding WHERE device_id=OLD.id AND valid_to IS NULL)) THEN
        RAISE EXCEPTION 'Close active EMS bindings before moving asset' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER ems_asset_move BEFORE UPDATE OF station_id ON device FOR EACH ROW EXECUTE FUNCTION check_ems_asset_move();
CREATE FUNCTION check_ems_point_binding() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    binding device_binding;
    point_device bigint;
    definition_namespace text;
    definition_type text;
    definition_source numeric;
BEGIN
    SELECT * INTO binding FROM device_binding WHERE id=NEW.device_binding_id FOR UPDATE;
    SELECT device_id INTO point_device FROM measurement_point WHERE id=NEW.measurement_point_id FOR SHARE;
    SELECT namespace,value_type,source_id INTO definition_namespace,definition_type,definition_source FROM point_definition WHERE id=NEW.definition_id;
    IF EXISTS (
    SELECT 1 FROM point_binding pb JOIN point_definition pd ON pd.id=pb.definition_id
    WHERE pb.device_binding_id=NEW.device_binding_id AND pb.id IS DISTINCT FROM NEW.id
    AND pd.namespace=definition_namespace AND pd.source_id=definition_source
    AND tstzrange(pb.valid_from,pb.valid_to,'[)') && tstzrange(NEW.valid_from,NEW.valid_to,'[)')
    ) THEN
        RAISE EXCEPTION 'Source position already mapped in another catalog version' USING ERRCODE='23514';
    END IF;
    IF binding.id IS NULL OR binding.device_id IS DISTINCT FROM point_device OR definition_type='unknown' OR
    definition_namespace='config' OR (definition_namespace='cabinet' AND binding.scope<>'cabinet') OR
    (definition_namespace='ems' AND binding.scope<>'ems') OR
    NOT(tstzrange(NEW.valid_from,NEW.valid_to,'[)') <@ tstzrange(binding.valid_from,binding.valid_to,'[)')) THEN
        RAISE EXCEPTION 'Point binding asset, namespace or period mismatch' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER ems_point_binding_guard BEFORE INSERT OR UPDATE ON point_binding FOR EACH ROW EXECUTE FUNCTION check_ems_point_binding();
