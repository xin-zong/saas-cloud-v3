-- EMS ingestion relations. Wire counters are arbitrary precision integers.
CREATE DOMAIN ems_counter AS numeric CHECK(VALUE >= 0 AND VALUE=trunc(VALUE) AND VALUE NOT IN ('NaN'::numeric,'Infinity'::numeric,'-Infinity'::numeric));
CREATE DOMAIN ems_positive_counter AS numeric CHECK(VALUE > 0 AND VALUE=trunc(VALUE) AND VALUE NOT IN ('NaN'::numeric,'Infinity'::numeric,'-Infinity'::numeric));
CREATE DOMAIN ems_uuid_v4 AS uuid CHECK(VALUE::text ~ '^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$');
CREATE DOMAIN ems_content_hash AS text CHECK(VALUE ~ '^[0-9a-f]{64}$');
CREATE TABLE ems_gateway (
    ems_uuid ems_uuid_v4 PRIMARY KEY,
    device_id bigint NOT NULL UNIQUE REFERENCES device(id)
);
-- Station is retained here as an historical authorization fact, rather than inferred from today's asset.
CREATE TABLE ems_binding_period (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ems_uuid ems_uuid_v4 NOT NULL REFERENCES ems_gateway,
    station_id bigint NOT NULL REFERENCES station,
    UNIQUE(id,ems_uuid),
    valid_from timestamptz NOT NULL,
    valid_to timestamptz,
    CHECK(valid_to IS NULL OR valid_to>valid_from),
    EXCLUDE USING gist(ems_uuid WITH =,tstzrange(valid_from,valid_to,'[)') WITH &&)
);
CREATE TABLE connection_state (
    ems_uuid ems_uuid_v4 PRIMARY KEY REFERENCES ems_gateway,
    connection_id ems_uuid_v4,
