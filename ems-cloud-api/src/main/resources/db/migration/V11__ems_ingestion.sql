CREATE FUNCTION ems_valid_u16_words(value jsonb) RETURNS boolean LANGUAGE sql IMMUTABLE AS $$
 SELECT CASE WHEN value IS NULL THEN true WHEN jsonb_typeof(value)<>'array' THEN false
 WHEN jsonb_array_length(value)<>4 THEN false ELSE NOT EXISTS(
 SELECT 1 FROM jsonb_array_elements(value) v WHERE CASE WHEN jsonb_typeof(v)<>'number' THEN true
 ELSE (v::text)::numeric<>trunc((v::text)::numeric) OR (v::text)::numeric NOT BETWEEN 0 AND 65535 END) END
$$;
